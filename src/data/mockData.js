// Calculate priority score from factors
export function calculatePriority(factors) {
  const {
    severity = 0,     // 0-30
    affectedPeople = 0, // 0-20
    recurrence = 0,   // 0-20
    waitingTime = 0,  // 0-15
    locationRisk = 0, // 0-15
  } = factors;
  return Math.min(100, severity + affectedPeople + recurrence + waitingTime + locationRisk);
}

// Get severity label from score
export function getSeverityLabel(score) {
  if (score >= 90) return 'Critical';
  if (score >= 75) return 'High';
  if (score >= 50) return 'Medium';
  return 'Low';
}

// Map severity string to color
export function getSeverityColor(severity) {
  switch (severity?.toLowerCase()) {
    case 'critical': return '#dc2626';
    case 'high': return '#ea580c';
    case 'medium': return '#ca8a04';
    case 'low': return '#16a34a';
    default: return '#64748b';
  }
}

